"""Read upstream model catalogs without generating completions or storing keys."""
import http.client
import json
import socket
import threading
import time
from urllib.parse import urlencode, urlsplit, urlunsplit

from .runner import resolve_public

_slots = threading.BoundedSemaphore(4)


def catalog_url(base):
    parsed = urlsplit(base)
    path = parsed.path.rstrip("/")
    for suffix in ("/chat/completions", "/messages"):
        if path.endswith(suffix):
            path = path[:-len(suffix)]
            break
    if not path:
        path = "/v1"
    if not path.endswith("/models"):
        path += "/models"
    return urlunsplit((parsed.scheme, parsed.netloc, path, "", ""))


def get_json(url, headers, timeout=20):
    parsed = urlsplit(url)
    # Query parameters below are generated by pagination, never taken from a user URL.
    address = resolve_public(urlunsplit((parsed.scheme, parsed.netloc, parsed.path, "", "")))
    connection_type = http.client.HTTPSConnection if parsed.scheme == "https" else http.client.HTTPConnection
    connection = connection_type(parsed.hostname, parsed.port, timeout=timeout)
    connection._create_connection = lambda target, timeout, source_address=None, **kw: socket.create_connection((address, target[1]), timeout, source_address)
    deadline = time.monotonic() + timeout
    try:
        connection.request("GET", parsed.path + ("?" + parsed.query if parsed.query else ""), headers={"Accept": "application/json", **headers})
        if connection.sock:
            connection.sock.settimeout(max(.01, deadline - time.monotonic()))
        response = connection.getresponse()
        if response.status in (401, 403):
            raise ValueError("密钥无效，或没有读取模型列表的权限")
        if response.status == 404:
            raise ValueError("接口未提供模型列表，请核对基础地址或手动填写模型 ID")
        if response.status >= 300:
            raise ValueError(f"读取模型列表失败（HTTP {response.status}），请稍后重试或手动填写")
        chunks, size = [], 0
        while True:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                raise TimeoutError()
            if connection.sock:
                connection.sock.settimeout(remaining)
            chunk = response.read1(32768)
            if not chunk:
                break
            size += len(chunk)
            if size > 2 * 1024 * 1024:
                raise ValueError("模型列表响应过大，请手动填写模型 ID")
            chunks.append(chunk)
        try:
            return json.loads(b"".join(chunks))
        except (ValueError, UnicodeDecodeError) as exc:
            raise ValueError("接口没有返回有效的模型列表，请手动填写模型 ID") from exc
    finally:
        connection.close()


def discover(base, protocol, key, transport=None):
    if not _slots.acquire(blocking=False):
        raise ValueError("模型识别请求较多，请稍后重试")
    try:
        transport = transport or get_json
        url = catalog_url(base)
        headers = {"x-api-key": key, "anthropic-version": "2023-06-01"} if protocol == "anthropic" else {"Authorization": "Bearer " + key}
        models, seen_cursors = set(), set()
        query = {"limit": 1000} if protocol == "anthropic" else {}
        deadline = time.monotonic() + 25
        has_more = False
        for page in range(5):
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                raise TimeoutError()
            data = transport(url + ("?" + urlencode(query) if query else ""), headers, timeout=min(20, remaining))
            rows = data.get("data") if isinstance(data, dict) else None
            if not isinstance(rows, list):
                raise ValueError("接口没有返回有效的模型列表，请手动填写模型 ID")
            for row in rows:
                value = row.get("id") if isinstance(row, dict) else None
                if not isinstance(value, str):
                    continue
                value = value.strip()
                # Apply the same ID boundaries as Station.models, and never return an echoed key.
                if value and len(value) <= 150 and not any(ord(c) < 32 for c in value) and key not in value:
                    models.add(value)
                if len(models) >= 5000:
                    break
            has_more = bool(data.get("has_more")) or len(models) >= 5000
            if not has_more or len(models) >= 5000:
                break
            cursor = data.get("last_id")
            if not isinstance(cursor, str) or not cursor or len(cursor) > 150 or cursor in seen_cursors:
                break
            seen_cursors.add(cursor)
            query.update(after_id=cursor)
        if not models:
            raise ValueError("没有识别到可用模型，请检查密钥权限或手动填写模型 ID")
        return {"models": sorted(models), "has_more": has_more}
    finally:
        _slots.release()
